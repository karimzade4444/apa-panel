import type { Metadata } from "next";
import "./globals.css";
import { Providers } from "./providers";

import { Inter, JetBrains_Mono } from "next/font/google";

const inter = Inter({
  subsets: ["latin", "cyrillic"],
  variable: "--font-inter",
});
const jetbrains = JetBrains_Mono({
  subsets: ["latin", "cyrillic"],
  variable: "--font-jetbrains",
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

// Ставит класс "dark" до отрисовки, чтобы не было мигания
const themeScript = `
  try {
    var t = localStorage.getItem("theme") || "dark";
    var preferences = localStorage.getItem("glassy-ui-preferences");
    if (preferences) {
      var savedTheme = JSON.parse(preferences).theme;
      if (savedTheme === "light" || savedTheme === "dark") t = savedTheme;
    }
    document.documentElement.classList.toggle("dark", t === "dark");
  } catch (e) {
    document.documentElement.classList.add("dark");
  }
`;

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="ru"
      suppressHydrationWarning
      className={`${inter.variable} ${jetbrains.variable} h-full antialiased`}
    >
      <head>
        <script dangerouslySetInnerHTML={{ __html: themeScript }} />
      </head>
      <body className="min-h-full flex bg-white text-slate-900 transition-colors duration-500 dark:bg-slate-950 dark:text-slate-100">
        <Providers>{children}</Providers>
      </body>
    </html>
  );
}
